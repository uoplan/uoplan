/** Locate @tabler/icons node arrays (resolve, else scan the pnpm store). */
function loadTablerNodes() {
  /** @param {string} rel */
  const tryResolve = (rel) => {
    try {
      return JSON.parse(readFileSync(require.resolve(`@tabler/icons/${rel}`), "utf8"));
    } catch {
      return null;
    }
  };
  let outline = tryResolve("tabler-nodes-outline.json");
  let filled = tryResolve("tabler-nodes-filled.json");
  if (outline && filled) return { outline, filled };

  const pnpmDir = join(repoRoot, "node_modules", ".pnpm");
  const match = existsSync(pnpmDir)
    ? readdirSync(pnpmDir).find((d) => d.startsWith("@tabler+icons@"))
    : undefined;
  if (!match) throw new Error("@tabler/icons not found (resolve + pnpm-store scan failed)");
  const base = join(pnpmDir, match, "node_modules", "@tabler", "icons");
  outline = JSON.parse(readFileSync(join(base, "tabler-nodes-outline.json"), "utf8"));
  filled = JSON.parse(readFileSync(join(base, "tabler-nodes-filled.json"), "utf8"));
  return { outline, filled };
}

function main() {
  const { outline, filled } = loadTablerNodes();
  /** @type {Record<string, { paths: string[]; filled: boolean }>} */
  const result = {};
  const missing = [];
  for (const [sf, [tabler, isFilled]] of Object.entries(MAP)) {
    const src = isFilled ? filled : outline;
    const nodes = src[tabler];
    if (!nodes) {
      missing.push(`${sf} -> ${tabler}${isFilled ? " (filled)" : ""}`);
      continue;
    }
    const paths = nodes
      .filter(([tag]) => tag === "path")
      .map(([, attrs]) => attrs.d)
      .filter(Boolean);
    result[sf] = { paths, filled: Boolean(isFilled) };
  }
  if (missing.length) {
    throw new Error(`Tabler icons not found:\n  ${missing.join("\n  ")}`);
  }

  const entries = Object.keys(result)
    .sort()
    .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(result[name])},`)
    .join("\n");
  const file = `// AUTO-GENERATED by scripts/gen-icon-paths.mjs — DO NOT EDIT.
// Tabler icon path data for the SF Symbol names used by <AppIcon /> on Android/web.
// Re-run: pnpm --filter native gen:icons

export interface TablerIconPaths {
  /** SVG path \`d\` strings, drawn at a 24x24 viewBox. */
  paths: string[];
  /** When true the icon is fill-based (solid); otherwise stroke-based (outline). */
  filled: boolean;
}

export const ICON_PATHS: Record<string, TablerIconPaths> = {
${entries}
};
`;
  const outPath = join(__dirname, "..", "src", "components", "icon-paths.generated.ts");
  writeFileSync(outPath, file);
  console.log(`Wrote ${Object.keys(result).length} icons -> ${outPath}`);
}

main();
