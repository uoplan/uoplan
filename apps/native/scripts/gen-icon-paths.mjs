/**
 * Generates `src/components/icon-paths.generated.ts` — a compact map of the SF
 * Symbol names the app uses (via <AppIcon />) to Tabler icon SVG path data.
 *
 * iOS renders SF Symbols natively (expo-symbols). Android/web have no SF Symbols,
 * so <AppIcon /> falls back to drawing these Tabler paths with react-native-svg.
 * We bake ONLY the icons we actually use into a committed file so the runtime
 * bundle stays tiny and apps/native needs no @tabler/icons dependency.
 *
 * Re-run after changing the icon set:  pnpm --filter native gen:icons
 */
